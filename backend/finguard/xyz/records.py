def _llm_topic(q: str, words: list[str]) -> tuple[str | None, str | None]:
    """Ask the configured LLM which *existing* filter the user's words mean. It can only pick from the fixed lists below;
    anything else is discarded, so it cannot invent data — the ledger query still produces every figure."""
    try:
        from finguard.llm.providers import LLMRequest, get_provider

        prov = get_provider()
        if prov.is_mock:
            return None, None
        topics = {k: v[0] for k, v in TOPIC_KEYS.items()}
        kinds = {k: v for k, v in KIND_LABEL.items() if k != "OPENING"}
        data = prov.complete(LLMRequest(
            "You map words from a finance question to filters of a company ledger. Reply with JSON only: "
            '{"topic": <one key of TOPICS or null>, "kind": <one key of KINDS or null>}. Use null when no filter clearly '
            "means the same thing. Never guess.",
            f"Question: {q}\nUnmatched words: {', '.join(words)}\nTOPICS: {topics}\nKINDS: {kinds}", "plan", 200)).json()
        t, k = data.get("topic"), data.get("kind")
        return (t if t in TOPIC_KEYS else None), (k if k in kinds else None)
    except Exception:                                  # the LLM is optional — any failure means "not understood"
        return None, None


def _resolve_leftover(st, rq: RQuery, a, b, q: str) -> tuple[list[str], list[str]]:
    """Match words no filter explained against the ledger itself: counterparty names, then descriptions; finally the LLM.
    Returns (how words were used, words that matched nothing)."""
    f, used, unknown = rq.filt, [], []
    for w in rq.leftover:
        stem = w[:-1] if w.endswith("s") and len(w) > 4 else w
        hits = tuple(p for p in PARTIES if any(t.lower().startswith(stem) for t in re.findall(r"[A-Za-z]+", p)))
        if hits and not f.parties and len(hits) <= 5:
            f.parties = hits
            used.append(f"“{w}” → {', '.join(hits)}")
            continue
        if not f.text and st.search(TxnFilter(**{**f.__dict__, "text": stem}), a, b, "recent", 1)[1]:
            f.text = stem
            used.append(f"“{w}” → descriptions containing “{stem}”")
            continue
        unknown.append(w)
    if unknown:
        topic, kind = _llm_topic(q, unknown)
        if topic or kind:
            if topic:
                spec = TOPIC_KEYS[topic][1]
                f.domain = spec.get("domain", f.domain)
                f.accounts = tuple(dict.fromkeys(f.accounts + spec.get("accounts", ())))
                rq.topics.append(topic)
            if kind and not f.kinds:
                f.kinds = rq.kinds = (kind,)
            used.append(f"“{' '.join(unknown)}” → {topic_label(topic) if topic else KIND_LABEL[kind]} (interpreted by the AI model)")
            unknown = []
    return used, unknown


def _kn(k: str, n: int) -> str:
    return f"{n:,} " + (KIND_LABEL[k].lower() if n == 1 else KIND_PLURAL.get(k, KIND_LABEL[k].lower() + "s"))


def _what(rq: RQuery) -> str:
    f = rq.filt
    topic = " / ".join(topic_label(t) for t in dict.fromkeys(rq.topics))
    kinds = " / ".join(KIND_PLURAL.get(k, KIND_LABEL[k].lower() + "s") for k in f.kinds) if f.kinds else "transactions"
    if f.kinds == OUT_KINDS:
        kinds = "outgoing payments"
    elif f.kinds == IN_KINDS:
        kinds = "incoming transactions"
    return f"{topic} {kinds}".strip() if topic else kinds


def _understood(rq: RQuery, label, used, unknown, shown, total) -> list[list[str]]:
    f = rq.filt
    out = []
    if f.domain:
        name, seg, vendors = DOMAINS[f.domain]
        out.append(["Domain", f"{name}: {seg} segment sales and receipts" + (f" + purchases from and payments to its suppliers "
                                                                              f"({', '.join(vendors)})" if vendors else "")])
    if f.accounts:
        out.append(["Category", account_names(f.accounts)])
    if f.kinds:
        out.append(["Type", ", ".join(KIND_LABEL[k] for k in f.kinds)])
    if f.parties:
        out.append(["Counterparty", ", ".join(f.parties)])
    if f.segment:
        out.append(["Segment", f.segment])
    if f.region:
        out.append(["Region", f.region])
    if f.min_amt is not None or f.max_amt is not None:
        out.append(["Amount", " and ".join(x for x in (f"at least {_fmt(f.min_amt)}" if f.min_amt is not None else "",
                                                        f"at most {_fmt(f.max_amt)}" if f.max_amt is not None else "") if x)])
    if f.text:
        out.append(["Text contains", f"“{f.text}”"])
    out.append(["Period", label or f"all recorded years ({_dt(DATA_START)} – {_dt(DATA_END)})"])
    adj = {"recent": "most recent first", "oldest": "oldest first", "largest": "largest first", "smallest": "smallest first"}
    out.append(["Shown", f"{shown:,} of {total:,} · {adj[rq.order]}"])
    if used:
        out.append(["Matched your words", "; ".join(used)])
    if unknown:
        out.append(["Not found in the ledger", ", ".join(f"“{w}”" for w in unknown)])
    return out


