"""Company records Q&A: everything about XYZ Ltd that is not a single computed metric.

Covers individual transactions (recent / largest / on a date / with a counterparty / by document reference), the mix of
transaction types, customers and vendors (activity, outstanding balances, who owes what), the company profile
(segments, regions, key figures), data coverage and the chart of accounts.

Like the metric engine, every fact is read from the ledger — two interchangeable stores implement the same queries:
  * SQLRecords    — PostgreSQL (what the API and the agent use)
  * MemoryRecords — the generator's in-memory ledger (independent path used by the tests)
Nothing is generated by a language model, and anything the ledger does not record (management, headcount, address…)
is reported as not available rather than guessed.
"""

