def _fmt(paise: int) -> str:
    from finguard.xyz.qa import fmt_short

    return fmt_short(Decimal(paise) / 100, "INR")


def _exact(paise: int) -> str:
    from finguard.xyz.qa import _indian

    return _indian(Decimal(paise) / 100)


def _dt(d: date) -> str:
    return f"{d.day} {d:%b %Y}"


def _span(rq: RQuery) -> tuple[date, date, str | None, list[str]]:
    """Date window for the query. Returns (start, end, label, assumptions)."""
    if rq.periods:
        return min(p.start for p in rq.periods), max(p.end for p in rq.periods), \
            (rq.periods[0].pretty if len(rq.periods) == 1 else f"{rq.periods[0].label} – {rq.periods[-1].label}"), \
            [p.assumption for p in rq.periods if p.assumption]
    return DATA_START, DATA_END, None, []


def _txn_table(rows: list[Row], title: str) -> dict:
    return {"type": "table", "title": title, "columns": ["Date", "Reference", "Type", "Counterparty", "Description", "Amount"],
            "rows": [[_dt(r.d), r.doc_ref, KIND_LABEL.get(r.kind, r.kind), r.counterparty or "—", r.description, _fmt(r.amount)]
                     for r in rows]}


def _ev(rid: str, label: str, accounts, formula: str, n: int | None = None, docs: list[str] | None = None) -> dict:
    return {"id": rid, "period": label, "accounts": list(accounts), "formula": formula, "journal_lines": n,
            "sample_documents": docs or []}


def _result(status: str, title: str, summary: str, blocks: list[dict], *, assumptions=(), limitations=(), sources=(),
            evidence=(), value=None, intent: str = "") -> dict:
    return {"status": status, "title": title, "summary": summary, "blocks": blocks, "assumptions": list(dict.fromkeys(assumptions)),
            "limitations": list(limitations), "sources": list(sources), "evidence": list(evidence), "value": value,
            "plan": {"metric": None, "operation": f"RECORDS:{intent}", "periods": []}}


