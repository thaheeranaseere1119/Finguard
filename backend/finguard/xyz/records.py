def _txn_overview(calc, st, rq: RQuery) -> dict:
    rows, total, tot_amt, groups = st.search(TxnFilter(), DATA_START, DATA_END, "recent", 5)
    by_kind: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    by_fy: dict[int, list[int]] = defaultdict(lambda: [0, 0])
    for (k, fy), (n, v) in groups.items():
        by_kind[k][0] += n
        by_kind[k][1] += v
        by_fy[fy][0] += n
        by_fy[fy][1] += v
    kinds = sorted(by_kind.items(), key=lambda x: -x[1][0])
    fys = sorted(by_fy)
    blocks = [{"type": "highlights", "items": [{"label": "Transactions recorded", "value": f"{total:,}",
                                                "note": f"{_dt(DATA_START)} – {_dt(DATA_END)}"},
                                               {"label": "Transaction types", "value": str(len(kinds))},
                                               {"label": "Latest entry", "value": _dt(rows[0].d), "note": rows[0].doc_ref}]},
              {"type": "table", "title": "All transactions by type", "columns": ["Type", "Count", "Total value"],
               "rows": [[KIND_LABEL.get(k, k), f"{n:,}", _fmt(v)] for k, (n, v) in kinds]},
              {"type": "table", "title": "Transactions per fiscal year", "columns": ["Fiscal year", "Count", "Total value"],
               "rows": [[f"FY{fy}", f"{by_fy[fy][0]:,}", _fmt(by_fy[fy][1])] for fy in fys],
               "chart": {"kind": "bar", "values": [float(Decimal(by_fy[fy][1]) / 100) for fy in fys],
                         "labels": [f"FY{fy}" for fy in fys]}},
              _txn_table(rows, "Latest 5 transactions"),
              {"type": "list", "title": "Ask for exactly what you need, for example", "items": TXN_EXAMPLES}]
    top = ", ".join(_kn(k, n) for k, (n, _) in kinds[:4])
    return _result("ANSWERED", "Transactions overview", f"XYZ Ltd's ledger holds {total:,} transactions from {_dt(DATA_START)} to "
                   f"{_dt(DATA_END)} — mostly {top}. Your question didn't name a type, domain, counterparty, amount or period, "
                   f"so here is the overview; ask e.g. “all hardware transactions in FY2025” or “sales above ₹10 lakh” for a "
                   f"specific list.", blocks,
                   sources=[{"label": "fin_journal_entries", "detail": f"{total:,} entries grouped by type and fiscal year"}],
                   evidence=[_ev("ledger:entries", f"{_dt(DATA_START)}..{_dt(DATA_END)}", [], "count of journal entries by kind and FY",
                                 total, [r.doc_ref for r in rows[:3]])],
                   value=[[r.d.isoformat(), r.doc_ref, r.kind, r.counterparty, r.description, str(Decimal(r.amount) / 100)] for r in rows],
                   intent="TXNS")


def _txn_search(calc, st, rq: RQuery) -> dict:
    if rq.filt is None:
        rq.filt = TxnFilter(kinds=rq.kinds, parties=(rq.party,) if rq.party else (), segment=rq.segment, region=rq.region)
    if rq.overview:
        return _txn_overview(calc, st, rq)
    a, b, label, assumptions = _span(rq)
    used, unknown = _resolve_leftover(st, rq, a, b, q=" ".join(rq.leftover)) if rq.leftover else ([], [])
    f = rq.filt
    substantive = not TxnFilter(segment=None, region=f.region, kinds=f.kinds, parties=f.parties, accounts=f.accounts,
                                domain=f.domain, min_amt=f.min_amt, max_amt=f.max_amt, text=f.text, ).empty() or f.segment
    if unknown and not substantive:
        return _result("CLARIFY", "No matching transactions",
                       f"I couldn't find anything in XYZ Ltd's ledger related to {', '.join(f'“{w}”' for w in unknown)}, so I "
                       f"won't show an unrelated list. Transactions can be filtered by business domain (hardware, cloud, "
                       f"software), category (rent, travel, marketing, salaries …), type (sales, receipts, purchases, vendor "
                       f"payments …), customer or vendor, region, amount and period.",
                       [{"type": "list", "title": "For example", "items": TXN_EXAMPLES}], intent="TXNS")
    rows, total, tot_amt, groups = st.search(f, a, b, rq.order, rq.limit if rq.explicit_limit or rq.singular else max(rq.limit, 25))
    if total <= 25 and not rq.explicit_limit and not rq.singular:
        rows = rows[:25]
    else:
        rows = rows[:rq.limit]
    what = _what(rq)
    scope = "".join(f" {w} {v}" for w, v in (("with", ", ".join(f.parties) if f.parties else None), ("in", f.segment),
                                            ("in the", f"{f.region} region" if f.region else None)) if v)
    when = (f" on {label}" if rq.periods and len(rq.periods) == 1 and rq.periods[0].kind == "DAY" else f" in {label}") if label else ""
    understood = {"type": "kv", "title": "Understood as", "items": _understood(rq, label, used, unknown, len(rows), total)}
    if not rows:
        hint = coverage_note()
        if f.min_amt is not None or f.max_amt is not None:      # say what *does* exist without the amount condition
            loose = TxnFilter(**{**f.__dict__, "min_amt": None, "max_amt": None})
            lo, n_all, _, _ = st.search(loose, a, b, "smallest", 1)
            hi = st.search(loose, a, b, "largest", 1)[0]
            if n_all:
                hint = (f"Without the amount condition there are {n_all:,}, ranging from {_fmt(lo[0].amount)} to "
                        f"{_fmt(hi[0].amount)}.")
        return _result("NO_DATA", f"No {what} found", f"No {what}{scope}{when} match all of these conditions in XYZ Ltd's ledger. "
                       f"{hint}", [understood], assumptions=assumptions, intent="TXNS")
    head = rows[0]
    adj = {"recent": "most recent", "oldest": "earliest", "largest": "largest", "smallest": "smallest"}[rq.order]
    one = (KIND_LABEL[f.kinds[0]].lower() if len(f.kinds) == 1 else "transaction") if f.kinds else "transaction"
    head_s = (f"The {adj} {one}{scope}{when} was {head.description} on {_dt(head.d)} ({head.doc_ref}, {_fmt(head.amount)}"
              + (f", {head.counterparty}" if head.counterparty and head.counterparty not in head.description
                 and head.counterparty not in f.parties else "") + ").")
    by_kind: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    by_fy: dict[int, list[int]] = defaultdict(lambda: [0, 0])
    for (k, fy), (n, v) in groups.items():
        by_kind[k][0] += n
        by_kind[k][1] += v
        by_fy[fy][0] += n
        by_fy[fy][1] += v
    kinds = sorted(by_kind.items(), key=lambda x: (-x[1][0], x[0]))
    count_s = f"{total:,} {what}{scope}{when} match" + ("es" if total == 1 else "") + f", worth {_fmt(tot_amt)} in total"
    if len(kinds) > 1:
        count_s += ": " + ", ".join(f"{_kn(k, n)} ({_fmt(v)})" for k, (n, v) in kinds[:4])
    count_s += "."
    if rq.singular and not rq.want_all:
        summary = head_s + f" ({total:,} matching in all.)"
    else:
        summary = (head_s + " " if rq.ordered else "") + count_s
        summary += (" All of them are listed below." if len(rows) == total else
                    f" The {len(rows)} {adj} are listed below" + (" — add a year, amount or type to narrow the list "
                                                                  "(Financials → Daily transactions pages through all of them)." if rq.want_all else "."))
    if unknown:
        summary += f" Note: {', '.join(f'“{w}”' for w in unknown)} matched nothing in the ledger and was not used as a filter."
    highlights = [{"label": "Matching transactions", "value": f"{total:,}", "note": label or "all recorded years"},
                  {"label": "Total value", "value": _fmt(tot_amt), "note": _exact(tot_amt)},
                  {"label": f"{adj.capitalize()} {one}", "value": _fmt(head.amount), "note": f"{_dt(head.d)} · {head.doc_ref}"}]
    blocks = [{"type": "highlights", "items": highlights}, understood,
              _txn_table(rows, f"{adj.capitalize()} {what}{scope}{when}" if len(rows) < total else f"All {what}{scope}{when}")]
    if len(kinds) > 1:
        blocks.append({"type": "table", "title": "Matching transactions by type", "columns": ["Type", "Count", "Total value"],
                       "rows": [[KIND_LABEL.get(k, k), f"{n:,}", _fmt(v)] for k, (n, v) in kinds]})
    if len(by_fy) > 1:
        fys = sorted(by_fy)
        blocks.append({"type": "table", "title": "Matching transactions per fiscal year", "columns": ["Fiscal year", "Count", "Total value"],
                       "rows": [[f"FY{fy}", f"{by_fy[fy][0]:,}", _fmt(by_fy[fy][1])] for fy in fys],
                       "chart": {"kind": "bar", "values": [float(Decimal(by_fy[fy][1]) / 100) for fy in fys],
                                 "labels": [f"FY{fy}" for fy in fys]}})
    lim = [LATEST_NOTE] if rq.order == "recent" and not label else []
    lim.append("Transaction amount = the entry's value (a sales invoice's value excludes its cost-of-sales posting).")
    return _result("ANSWERED", f"{what[:1].upper()}{what[1:]}{scope}" + (f" · {label}" if label else ""), summary, blocks,
                   assumptions=assumptions, limitations=lim,
                   sources=[{"label": "fin_journal_entries", "detail": f"{total:,} matching entries · e.g. {', '.join(r.doc_ref for r in rows[:3])}"}],
                   evidence=[_ev("ledger:entries", label or f"{_dt(DATA_START)}..{_dt(DATA_END)}", [],
                                 "journal entries matching: " + "; ".join(f"{k}={v}" for k, v in understood["items"][:-1]),
                                 total, [r.doc_ref for r in rows[:3]])],
                   value=[[r.d.isoformat(), r.doc_ref, r.kind, r.counterparty, r.description, str(Decimal(r.amount) / 100)] for r in rows],
                   intent="TXNS")


