def _prev_window(a: date, b: date) -> tuple[date, date] | None:
    from datetime import timedelta

    if a == DATA_START:
        return None
    if a.month == 4 and a.day == 1 and b.month == 3 and b.day == 31 and b.year == a.year + 1:      # a fiscal year
        return date(a.year - 1, 4, 1), date(b.year - 1, 3, 31)
    import calendar

    if a.day == 1 and b.day == calendar.monthrange(b.year, b.month)[1]:      # whole calendar months → same months before
        months = (b.year - a.year) * 12 + (b.month - a.month) + 1
        y, m = a.year, a.month - months
        while m <= 0:
            m += 12
            y -= 1
        pa = date(y, m, 1)
        pb = a - timedelta(days=1)
        return (pa, pb) if pa >= DATA_START else None
    span = (b - a).days + 1
    pb = a - timedelta(days=1)
    pa = pb - timedelta(days=span - 1)
    return (max(pa, DATA_START), pb) if pb >= DATA_START else None


