@dataclass
class RQuery:
    intent: str                     # TXNS DOC KINDS PARTY PARTIES OUTSTANDING PROFILE COVERAGE ACCOUNTS NOT_RECORDED
    kinds: tuple[str, ...] = ()
    party: str | None = None
    ref: str | None = None
    order: str = "recent"
    limit: int = 10
    role: str | None = None         # customer | vendor
    periods: list[Period] = field(default_factory=list)
    segment: str | None = None
    region: str | None = None
    focus: str | None = None        # PROFILE: segments | regions
    singular: bool = False
    filt: TxnFilter | None = None   # TXNS: every condition understood from the question
    topics: list[str] = field(default_factory=list)
    leftover: list[str] = field(default_factory=list)
    want_all: bool = False
    explicit_limit: bool = False
    overview: bool = False          # TXNS with no condition at all ("transactions")
    ordered: bool = False           # the question asked for recent / largest / oldest …


_NUM = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
        "fifteen": 15, "twenty": 20, "few": 5}
_TXN = r"transactions?|entries|entry|journal entr(?:y|ies)|postings?|vouchers?|ledger entr(?:y|ies)|(?:recent|latest) activit(?:y|ies)|dealings"
_CUE = (r"\b(?:recent|latest|newest|most recent|last|previous|lately|largest|biggest|highest|smallest|lowest|top|list|show|"
        r"display|individual|details?|made|happened|occurred|took place|recorded|done|posted|any|which|what|oldest|earliest|first)\b")
_NOT_RECORDED = re.compile(r"\b(ceo|cfo|coo|cto|founder|founded|chairman|chairperson|managing director|board of directors|directors?|"
                           r"management team|headquarter(?:s|ed)?|head office|address|located|location|phone|telephone|e-?mail id|"
                           r"website|share price|stock price|market cap(?:italisation|italization)?|listed on|ticker|"
                           r"head ?count|number of employees|how many employees|employee count|staff strength|auditors?)\b")


def _party(q: str) -> str | None:
    low = q.lower()
    return next((p for p in sorted(PARTIES, key=len, reverse=True) if re.search(rf"\b{re.escape(p.lower())}\b", low)), None)


def _kinds(low: str) -> tuple[str, ...]:
    for pat, kinds in KIND_WORDS:
        if re.search(pat, low):
            return kinds
    return ()


def _all_parties(low: str) -> tuple[str, ...]:
    return tuple(p for p in sorted(PARTIES, key=len, reverse=True) if re.search(rf"\b{re.escape(p.lower())}\b", low))


_ORDER_WORDS = (r"\b(?:most recent|recent|latest|newest|lately|last|previous|largest|biggest|highest|top|maximum|max|most expensive|"
                r"big|large|major|huge|significant|smallest|lowest|minimum|least|oldest|earliest|first)\b")
_INFLOW = r"\b(?:incoming (?:money|payments?|funds|transactions?)|money (?:coming in|that came in))\b"
_OUTFLOW = r"\b(?:outgoing (?:money|payments?|funds|transactions?)|money (?:going out|that went out))\b"
OUT_KINDS = ("PURCHASE", "VENDOR_PAYMENT", "EXPENSE", "PAYROLL", "CAPEX", "TAX_PAYMENT", "DIVIDEND", "INTEREST", "LOAN_REPAYMENT")
IN_KINDS = ("RECEIPT", "INTEREST_INCOME", "LOAN_DRAWDOWN")


def _txn_query(low: str, kinds, order, n, singular, explicit, base) -> RQuery:
    """A transaction query carrying every condition found in the question."""
    if re.search(_INFLOW, low):
        kinds = IN_KINDS
    elif re.search(_OUTFLOW, low):
        kinds = OUT_KINDS
    parties = _all_parties(low)
    consumed = [rf"\b(?:{_TXN})\b", _ORDER_WORDS, _INFLOW, _OUTFLOW, r"\b(?:region|zone|segment)s?\b", r"\b\d+\b",
                r"\b(?:" + "|".join(_NUM) + r")\b", *(pat for pat, _ in KIND_WORDS),
                *(rf"\b{re.escape(p.lower())}\b" for p in parties), *(re.escape(s.lower()) for s in SEGMENTS),
                *(rf"\b{r.lower()}\b" for r in REGIONS)]
    pz = txnfilter.parse(low, consumed, parties)
    f = TxnFilter(kinds=tuple(kinds), parties=parties, segment=base["segment"], region=base["region"], min_amt=pz.min_amt,
                  max_amt=pz.max_amt, text=pz.text)
    for t in pz.topics:
        spec = TOPIC_KEYS[t][1]
        if "domain" in spec and not f.domain:
            f.domain = spec["domain"]
            if DOMAINS[f.domain][1] == f.segment:
                f.segment = None                       # the domain already covers its segment
        if "accounts" in spec:
            f.accounts = tuple(dict.fromkeys(f.accounts + spec["accounts"]))
    if f.domain and kinds == ("EXPENSE", "PAYROLL"):
        f.kinds = ("PURCHASE", "VENDOR_PAYMENT", "CAPEX", "EXPENSE")   # "hardware costs" = what was bought / paid for it
    if f.accounts and kinds == ("EXPENSE", "PAYROLL"):
        f.kinds = ()                                   # the category already says which expense
    overview = (f.empty() and not base["periods"] and not explicit and not singular and not pz.leftover
                and not re.search(_ORDER_WORDS, low))
    limit = n if explicit or singular else 100 if pz.want_all else 10
    return RQuery("TXNS", kinds=f.kinds, order=order, limit=limit, singular=singular, filt=f, topics=pz.topics,
                  leftover=pz.leftover, want_all=pz.want_all, explicit_limit=explicit, overview=overview,
                  ordered=bool(re.search(_ORDER_WORDS, low)), **base)


def _limit(low: str) -> tuple[int, bool]:
    m = re.search(r"\b(?:last|latest|recent|top|first|largest|biggest|smallest|oldest|show|list|give me)\s+(\d{1,3}|"
                  + "|".join(_NUM) + r")\b", low) or re.search(r"\b(\d{1,3}|" + "|".join(_NUM) + r")\s+(?:most\s+)?"
                  r"(?:recent|latest|largest|biggest|smallest|oldest|last)\b", low)
    if m:
        n = _NUM.get(m[1]) or int(m[1])
        return max(1, min(n, 50)), n == 1
    singular = bool(re.search(r"\b(?:the|a|one|single)\s+(?:most\s+)?(?:recent|latest|last|largest|biggest|newest|highest|"
                              r"smallest|oldest|first)\s+(?:\w+\s){0,2}?(?:transaction|entry|payment|invoice|receipt|purchase|"
                              r"expense|sale|bill|dividend|posting)\b(?!s)", low))
    return 10, singular


def txn_word_early(low: str) -> bool:
    return bool(re.search(rf"\b(?:{_TXN})\b", low))


def detect(q: str, metric: str | None) -> RQuery | None:
    """Return a records query when the question is about records rather than a computed figure, else None.
    `metric` is what the metric engine understood with confidence (a lexicon match or a very sure classifier);
    weak record cues defer to it."""
    low = q.lower().replace("’", "'")
    periods = find_periods(q)
    party = _party(q)
    seg = next((s for s in SEGMENTS if s.lower() in low), None)
    reg = next((r for r in REGIONS if re.search(rf"\b{r.lower()}\s+(?:region|zone)\b|\bregion\s+{r.lower()}\b", low)
                or (r == "Export" and "export" in low)), None)
    base = dict(periods=periods, party=party, segment=seg, region=reg)

    if m := DOC_RE.search(q):
        return RQuery("DOC", ref=m[1].upper(), **{**base, "party": None})
    if _NOT_RECORDED.search(low) and not metric:
        return RQuery("NOT_RECORDED")
    if re.search(r"chart of accounts|\b(?:ledger|gl|general ledger) accounts\b|account codes|list (?:of |all |the )?accounts|"
                 r"what accounts|which accounts", low):
        return RQuery("ACCOUNTS", **base)
    if re.search(r"\bwhat data\b|data (?:available|coverage|range|do you have)|(?<!interest )(?<!debt service )\bcoverage of (?:the )?data\b|which (?:years|periods)|period covered|"
                 r"how far back|time ?range|date range|how (?:old|recent|up to date) is (?:the|your) data|latest data|"
                 r"data (?:until|till|up ?to)|as of when|how many (?:transactions|entries|records) (?:are there|in total|do you have)", low):
        return RQuery("COVERAGE", **base)
    if re.search(rf"\b(?:types?|kinds?|categor(?:y|ies)|breakdown|summary|split|mix) of (?:all )?(?:the )?(?:{_TXN})|"
                 rf"(?:{_TXN}) (?:by|per) (?:type|kind|category)|what (?:kinds?|types?|sorts?) of (?:{_TXN})", low):
        return RQuery("KINDS", **base)

    owes = re.search(r"\b(?:owes?|owed|owing|outstanding|unpaid|overdue|due from|due to|yet to (?:pay|be paid|receive)|pending "
                     r"(?:payments?|dues|invoices?)|dues)\b", low)
    grouping = re.search(r"\b(?:who|which|whom|list|top|largest|biggest|most|per|by|each|all)\b|customers|vendors|suppliers|clients", low)
    if metric and not re.search(r"\b(?:who|whom|which (?:customers?|vendors?|suppliers?|clients?))\b|\b(?:customers|vendors|suppliers|clients)\b", low):
        grouping = None                                # "days payable outstanding" is a ratio, not a who-owes-whom list
    if owes and (party or grouping):
        vendor_side = re.search(r"\bwe owe\b|\bdo we owe\b|\bowed? to\b|\bdue to\b|payables?|\bvendors?\b|\bsuppliers?\b|"
                                r"yet to pay|need to pay", low) and not re.search(r"owes? us|owed to us|due from|receivables?|customers?|clients?", low)
        if party:
            return RQuery("PARTY", **base)
        return RQuery("OUTSTANDING", role="vendor" if vendor_side else "customer", limit=_limit(low)[0], **base)

    spend_word = re.search(r"\b(spend\w*|spent|expenses?|expenditures?|costs?|outflows?|money (?:go|went)|where did (?:the |our )?money)\b", low)
    strong_bd = re.search(r"\b(breakdown|break ?down|categor\w*|department\w*|domains?|heads?|split|what did we spend|"
                          r"where did|areas?|wise|by type)\b", low)
    weak_bd = re.search(r"\b(each|every|by|details?|all|overall|summary|analysis)\b", low)
    specific = re.search(r"\b(marketing|advertis\w*|travel|rent|utilit\w*|electricity|salar\w*|payroll|wages|employee|"
                         r"software|it|professional|legal|audit fee|repairs?|depreciation|interest|tax|cogs|cost of goods|"
                         r"cost of services|capex|capital|cost of (?:revenue|sales|products|goods)|direct costs?|"
                         r"finance costs?|operating expenses|opex)\b", low)
    figure_q = re.search(r"\b(grow\w*|grew|rise|rose|increase\w*|decrease\w*|declin\w*|change|compare\w*|percent\w*|"
                         r"rank\w*|top|customers?|clients?|by what|margin|ratio|how much did .{1,40} (?:rise|grow|fall))\b|%", low)
    breakdown = (strong_bd and not (specific and figure_q)) or (weak_bd and not specific and not figure_q)
    if figure_q and specific:
        breakdown = None
    if spend_word and breakdown and not txn_word_early(low) and not re.search(r"\b(?:largest|biggest|smallest|recent|latest)\b", low):
        return RQuery("SPENDING", focus="segment" if re.search(r"\bsegments?\b", low) else
                      "department" if re.search(r"\bdepartment\w*|\bdomains?\b|\bteams?\b", low) else None, **base)
    txn_word = re.search(rf"\b(?:{_TXN})\b", low)
    kinds = IN_KINDS if re.search(_INFLOW, low) else OUT_KINDS if re.search(_OUTFLOW, low) else _kinds(low)
    counting = re.search(r"\b(?:how many|number of|count of|total number)\b", low)
    period_rank = re.search(r"\b(?:which|what|highest|lowest|best|worst|busiest|peak)\s+(?:month|quarter|day|date|year|week)\b|"
                            r"\bby (?:month|quarter|year|customer|segment|region)\b|\bwhich (?:customer|client|segment|region)\b", low)
    order = ("largest" if re.search(r"\b(?:largest|biggest|highest|top|maximum|max|most expensive|big|large|major|huge|"
                                    r"significant)\b", low)
             else "smallest" if re.search(r"\b(?:smallest|lowest|minimum|least)\b", low)
             else "oldest" if re.search(r"\b(?:oldest|earliest|first)\b", low) else "recent")
    if re.search(r"\b(?:categor(?:y|ies)|heads?|line items?|types?|accounts?)\b", low) and not txn_word:
        kinds = ()                                     # "biggest expense category" is a breakdown, not a transaction list
    n, singular = _limit(low)
    explicit = bool(re.search(r"\b(?:last|latest|recent|top|first|largest|biggest|smallest|oldest|show|list|give me)\s+(?:\d{1,3}|"
                              + "|".join(_NUM) + r")\b|\b(?:\d{1,3}|" + "|".join(_NUM) + r")\s+(?:most\s+)?"
                              r"(?:recent|latest|largest|biggest|smallest|oldest|last)\b", low))
    txn = lambda: _txn_query(low, kinds, order, n, singular, explicit, base)  # noqa: E731

    if txn_word and not counting and not period_rank:
        return txn()
    if txn_word and counting and (party or seg or reg or kinds) and not metric:
        return txn()
    if txn_word and counting and (
            any(re.search(pat, low) for _, pat, _, _ in txnfilter.TOPICS) or txnfilter.amount_range(low)[:2] != (None, None)):
        return txn()                                   # "how many hardware transactions" — count of the filtered set
    if kinds and not counting and not period_rank and (
            txnfilter.amount_range(low)[:2] != (None, None)
            or (re.search(r"\b(?:all|every)\b", low) and re.search(r"\b(?:list|show|display|give|gimme|fetch|get|find|pull)\b", low))):
        return txn()                                   # "all hardware sales above 10 lakh" lists entries, not a revenue figure
    if kinds and not counting and not period_rank and re.search(_CUE, low) and (
            re.search(r"\b(?:recent|latest|newest|lately|last|previous)\b(?!\s+(?:\d+|two|three|four|five|six|twelve)?\s*"
                      r"(?:fiscal|financial|years?|quarters?|months?|weeks?|days?|fy))", low)
            or re.search(r"\b(?:largest|biggest|big|large|major|huge|significant|smallest|single|individual|oldest|earliest)\s+"
                         r"(?:\w+\s){0,2}?(?:sales?|invoices?|receipts?|"
                         r"payments?|purchases?|expenses?|bills?|transactions?|dividends?|capex|salar(?:y|ies))\b", low)
            or (not metric and (periods or party or re.search(r"\b(?:list|show|display|details?|made|happened|occurred|took place)\b", low)))):
        return txn()

    # weaker cues: only when the metric engine found nothing to compute
    if metric:
        return None
    if party:
        return RQuery("PARTY", **base)
    if re.search(r"\b(?:customers?|clients?|buyers?)\b", low):
        return RQuery("PARTIES", role="customer", **base)
    if re.search(r"\b(?:vendors?|suppliers?|payees?)\b", low):
        return RQuery("PARTIES", role="vendor", **base)
    if re.search(r"\bsegments?\b|lines? of business|business (?:lines?|units?)|\bproducts?\b|what (?:does|do) (?:xyz|we|the company) "
                 r"(?:sell|offer|do)|offerings", low):
        return RQuery("PROFILE", focus="segments", **base)
    if re.search(r"\bregions?\b|\bgeograph|where (?:does|do) (?:xyz|we|the company) (?:sell|operate)|markets?\b", low):
        return RQuery("PROFILE", focus="regions", **base)
    if re.search(r"\b(?:about|overview|profile|summary|snapshot|introduc|describe|details?|information|info|background|"
                 r"at a glance|highlights|business|company|xyz|organi[sz]ation|firm|performance|doing|status|health)\b", low):
        return RQuery("PROFILE", **base)
    if kinds:
        return txn()
    return None


