class MemoryRecords:
    def __init__(self, ledger) -> None:
        amt: dict[int, int] = defaultdict(int)
        self.debits: dict[int, set[str]] = defaultdict(set)
        self.party_bal: dict[str, dict[str, list[tuple[date, int]]]] = {"1100": defaultdict(list), "2000": defaultdict(list)}
        self.n_lines = len(ledger.lines)
        for l in ledger.lines:
            if l.account not in COST_ACCOUNTS:
                amt[l.entry_id] += l.debit
            if l.debit > 0:
                self.debits[l.entry_id].add(l.account)
            if l.account in self.party_bal and l.counterparty:
                self.party_bal[l.account][l.counterparty].append((l.d, l.debit - l.credit))
        self.rows = [Row(e.id, e.d, e.doc_ref, e.kind, e.description, e.counterparty, e.segment, e.region, amt[e.id])
                     for e in ledger.entries]

    def bounds(self) -> tuple[date, date, int, int]:
        return min(r.d for r in self.rows), max(r.d for r in self.rows), len(self.rows), self.n_lines

    def _sel(self, start, end, kinds, party, segment=None, region=None):
        return [r for r in self.rows if start <= r.d <= end and (not kinds or r.kind in kinds)
                and (not party or r.counterparty == party) and (not segment or r.segment == segment)
                and (not region or r.region == region)]

    def find(self, start, end, kinds=(), party=None, ref=None, order="recent", limit=10, segment=None, region=None):
        if ref:
            rows = [r for r in self.rows if r.doc_ref.upper() == ref.upper()]
            return rows, len(rows), sum(r.amount for r in rows)
        rows = self._sel(start, end, kinds, party, segment, region)
        key = {"recent": lambda r: (r.d, r.id), "oldest": lambda r: (r.d, r.id), "largest": lambda r: (r.amount, r.d, r.id),
               "smallest": lambda r: (r.amount, r.d, r.id)}[order]
        out = sorted(rows, key=key, reverse=order in ("recent", "largest"))
        return out[:limit], len(rows), sum(r.amount for r in rows)

    def search(self, f: TxnFilter, start, end, order="recent", limit=10):
        """Entries matching every condition of `f`: (rows, count, total, groups) — groups = {(kind, fy): (n, amount)}."""
        rows = [r for r in self.rows if start <= r.d <= end and f.matches(r, self.debits[r.id])]
        groups: dict[tuple[str, int], list[int]] = defaultdict(lambda: [0, 0])
        for r in rows:
            g = groups[(r.kind, fy_of(r.d))]
            g[0] += 1
            g[1] += r.amount
        key = {"recent": lambda r: (r.d, r.id), "oldest": lambda r: (r.d, r.id), "largest": lambda r: (r.amount, r.d, r.id),
               "smallest": lambda r: (r.amount, r.d, r.id)}[order]
        out = sorted(rows, key=key, reverse=order in ("recent", "largest"))
        return out[:limit], len(rows), sum(r.amount for r in rows), {k: tuple(v) for k, v in groups.items()}

    def kind_summary(self, start, end, party=None):
        agg: dict[str, list[int]] = defaultdict(lambda: [0, 0])
        for r in self._sel(start, end, (), party):
            agg[r.kind][0] += 1
            agg[r.kind][1] += r.amount
        return sorted(((k, n, a) for k, (n, a) in agg.items()), key=lambda x: (-x[1], x[0]))

    def by_party(self, kinds, start, end):
        agg: dict[str, list[int]] = defaultdict(lambda: [0, 0])
        for r in self._sel(start, end, kinds, None):
            if r.counterparty:
                agg[r.counterparty][0] += 1
                agg[r.counterparty][1] += r.amount
        return {k: (n, a) for k, (n, a) in agg.items()}

    def party_balances(self, account, as_of):
        return {p: sum(v for d, v in xs if d <= as_of) for p, xs in self.party_bal[account].items()}

    def party_dates(self, party):
        ds = [r.d for r in self.rows if r.counterparty == party]
        return (min(ds), max(ds)) if ds else (None, None)


class SQLRecords:
    _AMT = "(SELECT COALESCE(SUM(CASE WHEN l.account_code IN ('5000','5100') THEN 0 ELSE l.debit END), 0) " \
           "FROM fin_journal_lines l WHERE l.entry_id = e.id)"

    _SUM = "COALESCE(SUM(CASE WHEN l.account_code IN ('5000','5100') THEN 0 ELSE l.debit END), 0)"

    def __init__(self, db, org_id) -> None:
        self.db, self.org = db, org_id

    def _q(self, sql, **p):
        from sqlalchemy import text

        return self.db.execute(text(sql), {"o": self.org, **p}).all()

    def bounds(self):
        a, b, n = self._q("SELECT MIN(entry_date), MAX(entry_date), COUNT(*) FROM fin_journal_entries WHERE org_id = :o")[0]
        nl = self._q("SELECT COUNT(*) FROM fin_journal_lines WHERE org_id = :o")[0][0]
        return a, b, int(n), int(nl)

    @staticmethod
    def _where(kinds, party, segment, region) -> str:
        w = " AND e.entry_date BETWEEN :a AND :b"
        if kinds:
            w += " AND e.kind = ANY(:k)"
        if party:
            w += " AND e.counterparty = :cp"
        if segment:
            w += " AND e.segment = :seg"
        if region:
            w += " AND e.region = :reg"
        return w

    @staticmethod
    def _row(r) -> Row:
        return Row(r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], int(Decimal(r[8]) * 100))

    def find(self, start, end, kinds=(), party=None, ref=None, order="recent", limit=10, segment=None, region=None):
        cols = f"e.id, e.entry_date, e.doc_ref, e.kind, e.description, e.counterparty, e.segment, e.region, {self._AMT} AS amount"
        if ref:
            rows = [self._row(r) for r in self._q(f"SELECT {cols} FROM fin_journal_entries e WHERE e.org_id = :o "
                                                  "AND upper(e.doc_ref) = upper(:r)", r=ref)]
            return rows, len(rows), sum(r.amount for r in rows)
        p = {"a": start, "b": end, "k": list(kinds), "cp": party, "seg": segment, "reg": region, "n": limit}
        w = self._where(kinds, party, segment, region)
        ob = {"recent": "e.entry_date DESC, e.id DESC", "oldest": "e.entry_date, e.id", "largest": "amount DESC, e.entry_date DESC, e.id DESC",
              "smallest": "amount, e.entry_date, e.id"}[order]
        rows = [self._row(r) for r in self._q(f"SELECT {cols} FROM fin_journal_entries e WHERE e.org_id = :o{w} ORDER BY {ob} LIMIT :n", **p)]
        n, tot = self._q(f"SELECT COUNT(*), COALESCE(SUM(CASE WHEN l.account_code IN ('5000','5100') THEN 0 ELSE l.debit END), 0) "
                         f"FROM fin_journal_entries e JOIN fin_journal_lines l ON l.entry_id = e.id WHERE e.org_id = :o{w}", **p)[0]
        cnt = self._q(f"SELECT COUNT(*) FROM fin_journal_entries e WHERE e.org_id = :o{w}", **p)[0][0]
        return rows, int(cnt), int(Decimal(tot) * 100)

    def search(self, f: TxnFilter, start, end, order="recent", limit=10):
        w, p = f.sql()
        having = []
        if f.accounts:
            having.append("bool_or(l.debit > 0 AND l.account_code = ANY(:f_acc))")
            p["f_acc"] = list(f.accounts)
        if f.min_amt is not None:
            having.append(f"{self._SUM} >= :f_min")
            p["f_min"] = Decimal(f.min_amt) / 100
        if f.max_amt is not None:
            having.append(f"{self._SUM} <= :f_max")
            p["f_max"] = Decimal(f.max_amt) / 100
        cte = (f"WITH m AS (SELECT e.id, e.entry_date, e.doc_ref, e.kind, e.description, e.counterparty, e.segment, e.region, "
               f"{self._SUM} AS amount FROM fin_journal_entries e JOIN fin_journal_lines l ON l.entry_id = e.id "
               f"WHERE e.org_id = :o AND e.entry_date BETWEEN :a AND :b{w} GROUP BY e.id"
               + (" HAVING " + " AND ".join(having) if having else "") + ") ")
        ob = {"recent": "entry_date DESC, id DESC", "oldest": "entry_date, id", "largest": "amount DESC, entry_date DESC, id DESC",
              "smallest": "amount, entry_date, id"}[order]
        p.update(a=start, b=end, n=limit)
        rows = [self._row(r) for r in self._q(cte + f"SELECT * FROM m ORDER BY {ob} LIMIT :n", **p)]
        groups = {}
        for k, fy, n, amt in self._q(cte + "SELECT kind, CAST(EXTRACT(YEAR FROM entry_date) AS INT) + "
                                     "CASE WHEN EXTRACT(MONTH FROM entry_date) >= 4 THEN 1 ELSE 0 END, COUNT(*), SUM(amount) "
                                     "FROM m GROUP BY 1, 2", **p):
            groups[(k, int(fy))] = (int(n), int(Decimal(amt) * 100))
        return rows, sum(n for n, _ in groups.values()), sum(a for _, a in groups.values()), groups

    def kind_summary(self, start, end, party=None):
        w = self._where((), party, None, None)
        rows = self._q("SELECT e.kind, COUNT(DISTINCT e.id), COALESCE(SUM(CASE WHEN l.account_code IN ('5000','5100') THEN 0 "
                       f"ELSE l.debit END), 0) FROM fin_journal_entries e JOIN fin_journal_lines l ON l.entry_id = e.id "
                       f"WHERE e.org_id = :o{w} GROUP BY e.kind ORDER BY 2 DESC, 1", a=start, b=end, cp=party)
        return [(k, int(n), int(Decimal(a) * 100)) for k, n, a in rows]

    def by_party(self, kinds, start, end):
        rows = self._q("SELECT e.counterparty, COUNT(DISTINCT e.id), COALESCE(SUM(CASE WHEN l.account_code IN ('5000','5100') "
                       "THEN 0 ELSE l.debit END), 0) FROM fin_journal_entries e JOIN fin_journal_lines l ON l.entry_id = e.id "
                       "WHERE e.org_id = :o AND e.kind = ANY(:k) AND e.entry_date BETWEEN :a AND :b AND e.counterparty IS NOT NULL "
                       "GROUP BY 1", k=list(kinds), a=start, b=end)
        return {p: (int(n), int(Decimal(a) * 100)) for p, n, a in rows}

    def party_balances(self, account, as_of):
        rows = self._q("SELECT counterparty, SUM(debit - credit) FROM fin_journal_lines WHERE org_id = :o AND account_code = :acc "
                       "AND entry_date <= :d AND counterparty IS NOT NULL GROUP BY 1", acc=account, d=as_of)
        return {p: int(Decimal(v) * 100) for p, v in rows}

    def party_dates(self, party):
        a, b = self._q("SELECT MIN(entry_date), MAX(entry_date) FROM fin_journal_entries WHERE org_id = :o AND counterparty = :cp",
                       cp=party)[0]
        return a, b


def store_for(calc: Calc):
    s = calc.s
    if isinstance(s, SQLSource):
        return SQLRecords(s.db, s.org)
    if isinstance(s, MemorySource):
        if not hasattr(s, "_records"):
            s._records = MemoryRecords(s.ledger)
        return s._records
    raise TypeError("unsupported ledger source")


