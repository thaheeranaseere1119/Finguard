def run(calc: Calc, q: str, rq: RQuery) -> dict:
    st = store_for(calc)
    bad = [p for p in rq.periods if not in_range(p)]
    if bad:
        return _result("NO_DATA", "No data for that period", f"There is no XYZ Ltd data for {', '.join(p.label for p in bad)}. "
                       f"{coverage_note()}", [], intent=rq.intent)
    return {"TXNS": _txns, "DOC": _txns, "KINDS": _kinds_answer, "PARTY": _party_answer, "PARTIES": _parties,
            "OUTSTANDING": _outstanding, "PROFILE": _profile, "COVERAGE": _coverage, "ACCOUNTS": _accounts,
            "SPENDING": _spending,
            "NOT_RECORDED": _not_recorded}[rq.intent](calc, st, rq)


def _txns(calc, st, rq: RQuery) -> dict:
    a, b, label, assumptions = _span(rq)
    rows, total, tot_amt = st.find(a, b, rq.kinds, rq.party, rq.ref, rq.order, rq.limit, rq.segment, rq.region)
    what = " / ".join(KIND_PLURAL.get(k, KIND_LABEL[k].lower() + "s") for k in rq.kinds) if rq.kinds else "transactions"
    scope = "".join(f" {w} {v}" for w, v in (("with", rq.party), ("in", rq.segment), ("in the", f"{rq.region} region" if rq.region else None)) if v)
    when = (f" on {label}" if rq.periods and len(rq.periods) == 1 and rq.periods[0].kind == "DAY" else f" in {label}") if label else ""
    if rq.intent == "DOC":
        if not rows:
            return _result("NO_DATA", f"No document {rq.ref}", f"No transaction with reference {rq.ref} exists in XYZ Ltd's ledger.", [],
                           intent="DOC")
        r = rows[0]
        return _result("ANSWERED", f"Transaction {r.doc_ref}", f"{r.doc_ref} is a {KIND_LABEL.get(r.kind, r.kind).lower()} dated "
                       f"{_dt(r.d)}: {r.description}, {_fmt(r.amount)}.",
                       [{"type": "kv", "items": [["Date", _dt(r.d)], ["Type", KIND_LABEL.get(r.kind, r.kind)], ["Description", r.description],
                                                 ["Counterparty", r.counterparty or "—"], ["Segment", r.segment or "—"],
                                                 ["Region", r.region or "—"], ["Amount", f"{_fmt(r.amount)} ({_exact(r.amount)})"]]}],
                       sources=[{"label": r.doc_ref, "detail": f"journal entry #{r.id}"}],
                       evidence=[_ev(f"ledger:entry:{r.doc_ref}", _dt(r.d), [], "journal entry", None, [r.doc_ref])], intent="DOC")
    return _txn_search(calc, st, rq)


