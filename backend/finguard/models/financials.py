"""Company financial ledger (double-entry) used by the finance agent's grounded Q&A.

Every amount the agent reports is aggregated from these rows; nothing is generated by a language model.
"""

from __future__ import annotations

import uuid
from datetime import date
from decimal import Decimal

from sqlalchemy import REAL, BigInteger, Date, ForeignKey, Index, Integer, Numeric, String, Text, UniqueConstraint
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column

from finguard.core.db import Base


class FinAccount(Base):
    __tablename__ = "fin_accounts"
    __table_args__ = (UniqueConstraint("org_id", "code", name="uq_fin_account_code"),)
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    org_id: Mapped[uuid.UUID] = mapped_column(PG_UUID(as_uuid=True), ForeignKey("organizations.id"), nullable=False)
    code: Mapped[str] = mapped_column(String(8), nullable=False)
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    type: Mapped[str] = mapped_column(String(12), nullable=False)       # ASSET LIABILITY EQUITY REVENUE EXPENSE
    statement: Mapped[str] = mapped_column(String(4), nullable=False)   # BS | IS


class FinJournalEntry(Base):
    __tablename__ = "fin_journal_entries"
    __table_args__ = (Index("ix_fin_entries_org_date", "org_id", "entry_date"),
                      Index("ix_fin_entries_org_kind_date", "org_id", "kind", "entry_date"))
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    org_id: Mapped[uuid.UUID] = mapped_column(PG_UUID(as_uuid=True), ForeignKey("organizations.id"), nullable=False)
    entry_date: Mapped[date] = mapped_column(Date, nullable=False)
    doc_ref: Mapped[str] = mapped_column(String(32), nullable=False)
    kind: Mapped[str] = mapped_column(String(24), nullable=False)       # SALE RECEIPT PURCHASE VENDOR_PAYMENT PAYROLL ...
    description: Mapped[str] = mapped_column(String(200), nullable=False)
    counterparty: Mapped[str | None] = mapped_column(String(120))
    segment: Mapped[str | None] = mapped_column(String(40))
    region: Mapped[str | None] = mapped_column(String(20))
    cf_category: Mapped[str | None] = mapped_column(String(12))         # OPERATING INVESTING FINANCING (cash entries)


class FinJournalLine(Base):
    __tablename__ = "fin_journal_lines"
    __table_args__ = (Index("ix_fin_lines_org_account_date", "org_id", "account_code", "entry_date"),
                      Index("ix_fin_lines_entry", "entry_id"))
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    org_id: Mapped[uuid.UUID] = mapped_column(PG_UUID(as_uuid=True), nullable=False)
    entry_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("fin_journal_entries.id"), nullable=False)
    entry_date: Mapped[date] = mapped_column(Date, nullable=False)      # denormalized for fast period aggregation
    account_code: Mapped[str] = mapped_column(String(8), nullable=False)
    debit: Mapped[Decimal] = mapped_column(Numeric(18, 2), nullable=False, default=0)
    credit: Mapped[Decimal] = mapped_column(Numeric(18, 2), nullable=False, default=0)
    segment: Mapped[str | None] = mapped_column(String(40))
    region: Mapped[str | None] = mapped_column(String(20))
    counterparty: Mapped[str | None] = mapped_column(String(120))


class KBDocument(Base):
    """A document in the company knowledge base (profile, policy, monthly log, board minutes, dossier, daily log…)."""
    __tablename__ = "kb_documents"
    __table_args__ = (UniqueConstraint("org_id", "doc_key", name="uq_kb_doc_key"),)
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    org_id: Mapped[uuid.UUID] = mapped_column(PG_UUID(as_uuid=True), ForeignKey("organizations.id"), nullable=False)
    doc_key: Mapped[str] = mapped_column(String(80), nullable=False)
    doc_type: Mapped[str] = mapped_column(String(32), nullable=False)
    title: Mapped[str] = mapped_column(String(300), nullable=False)
    period_start: Mapped[date | None] = mapped_column(Date)
    period_end: Mapped[date | None] = mapped_column(Date)
    entities: Mapped[list] = mapped_column(JSONB, nullable=False, default=list)


class KBChunk(Base):
    """A retrievable chunk: text (full-text indexed by Postgres) plus a local semantic embedding."""
    __tablename__ = "kb_chunks"
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=True)
    org_id: Mapped[uuid.UUID] = mapped_column(PG_UUID(as_uuid=True), nullable=False)
    document_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("kb_documents.id", ondelete="CASCADE"), nullable=False)
    chunk_no: Mapped[int] = mapped_column(Integer, nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    embedding: Mapped[list | None] = mapped_column(ARRAY(REAL))
